#if UNITY_IOS
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEditor.iOS.Xcode;
using UnityEngine;

namespace RiseOn.Consent.Editor {
    /// <summary>
    /// Writes what the consent flow reads from the app: the AdMob app id and the tracking prompt in Info.plist, the prompt's translations in each language's InfoPlist.strings, and the ATT framework.<br/>
    /// It runs after every other build step it can, so its values are the ones the app keeps, and it stops the build when an earlier step left a different value there, since that step's plugin then expects a value the app will not have.
    /// </summary>
    internal sealed class ConsentIOSPostprocess : IPostprocessBuildWithReport {
        private const string AppIdKey    = "GADApplicationIdentifier";
        private const string TrackingKey = "NSUserTrackingUsageDescription";
        private const string StringsName = "InfoPlist.strings";
        private const string Header      = "/* Generated by com.riseon.consent */\n";

        public int callbackOrder => int.MaxValue;

        public void OnPostprocessBuild(BuildReport report) {
            if (report.summary.platform is not BuildTarget.iOS) return;

            var buildPath = report.summary.outputPath;
            var settings  = ConsentSettingsProvider.Find();
            var written   = Written.Read(buildPath);
            var tracking  = settings.ChildDirected ? null : TrackingPrompts.DefaultOf(settings);
            var conflicts = new List<string>();

            var plistPath = Path.Combine(buildPath, "Info.plist");
            var plist     = new PlistDocument();
            plist.ReadFromFile(plistPath);
            Claim(AppIdKey, settings.AdMobAppIdIOS, written.appId);
            Claim(TrackingKey, tracking, written.tracking);

            var projectPath = PBXProject.GetPBXProjectPath(buildPath);
            var project     = new PBXProject();
            project.ReadFromFile(projectPath);

            // Every language the app gets a file for, Consent asks in, or Consent wrote last time, by TrackingPrompts.Key.
            var found     = AppStrings(buildPath, File.ReadAllText(projectPath), project.GetResourcesBuildPhaseByTarget(project.GetUnityMainTargetGuid()));
            var ours      = settings.ChildDirected ? new Dictionary<string, (string code, string text)>() : TrackingPrompts.All(settings).ToDictionary(language => TrackingPrompts.Key(language.code));
            var languages = ours.Keys.Concat(written.languages.Select(language => TrackingPrompts.Key(language.code))).Concat(found.Keys).Distinct().ToList();

            var changes   = new List<Action>();
            var removed   = new List<string>();
            var untracked = new List<string>();
            var now       = new Written { appId = settings.AdMobAppIdIOS, tracking = tracking, created = written.created.ToList() };
            foreach (var key in languages) {
                var code = ours.TryGetValue(key, out var language) ? language.code : written.Language(key)?.code ?? Path.GetFileNameWithoutExtension(Path.GetDirectoryName(found[key][0].Path));
                var text = ours.ContainsKey(key) ? language.text : null;
                Localize(key, code, text, written.Language(key)?.text);
                if (text != null) now.languages.Add(new Language { code = code, text = text });
            }

            if (conflicts.Count > 0) {
                throw new BuildFailedException($"{nameof(ConsentIOSPostprocess)}: other build steps wrote values Consent owns; remove them there, Consent writes them itself:\n- " + string.Join("\n- ", conflicts));
            }

            foreach (var change in changes) change();
            project.AddFrameworkToProject(project.GetUnityFrameworkTargetGuid(), "AppTrackingTransparency.framework", true);
            project.WriteToFile(projectPath);
            if (removed.Count > 0) File.WriteAllText(projectPath, XcodeResources.Remove(File.ReadAllText(projectPath), removed));
            plist.WriteToFile(plistPath);
            now.Write(buildPath);

            if (untracked.Count > 0) {
                Debug.LogWarning($"{nameof(ConsentIOSPostprocess)}: the app has {string.Join(", ", untracked)} but no tracking prompt in them, so players in those languages read the default one, Info.plist's; add them in Project Settings > RiseOn > Consent.");
            }

            // Info.plist: the value Consent keeps there, null for none.
            void Claim(string key, string value, string previous) {
                var existing = plist.root.values.TryGetValue(key, out var element) ? element : null;
                if (existing != null && !(existing is PlistElementString text && (text.value == value || text.value == previous))) {
                    conflicts.Add($"Info.plist {key} is {Describe(existing)}, Consent's is {Quote(value)}");
                }

                if (value == null) {
                    plist.root.values.Remove(key);
                } else {
                    plist.root.SetString(key, value);
                }
            }

            // One language's InfoPlist.strings, the file the app gets for it whoever made it: it holds Consent's line,
            // or none; a file of Consent's own goes with its folder when its language goes, since the App Store lists
            // every .lproj folder of the app as a language the game supports.
            void Localize(string key, string code, string value, string previous) {
                var files = found.TryGetValue(key, out var list) ? list : new List<XcodeResources.Entry>();
                if (files.Count > 1) {
                    conflicts.Add($"{code}: the app would get {files.Count} {StringsName} files ({string.Join(", ", files.Select(entry => entry.Path))}), which Xcode cannot copy to one place");
                    return;
                }

                var file = files.Count == 1 ? files[0].Path : $"{code}.lproj/{StringsName}";
                var path = Path.Combine(buildPath, file);
                var (text, encoding) = File.Exists(path) ? Read(path) : (null, new UTF8Encoding(false));

                // A build that appends puts back the files an earlier build of this project had, Consent's deleted
                // ones too, measured with Unity 6000.3: the reference returns without its file, and Xcode stops on it.
                if (text == null && value == null && files.Count == 1 && !files[0].Folder && written.Created(key)) {
                    removed.Add(files[0].Guid);
                    return;
                }

                if (text != null && text.StartsWith(Header)) {
                    if (!now.Created(key)) now.created.Add(code);
                    if (value != null) {
                        changes.Add(() => File.WriteAllText(path, StringsFile.Set(Header, TrackingKey, value), encoding));
                        return;
                    }

                    if (files.Count == 1 && !files[0].Folder) removed.Add(files[0].Guid);
                    changes.Add(() => {
                        File.Delete(path);
                        var folder = Path.GetDirectoryName(path)!;
                        if (!Directory.EnumerateFileSystemEntries(folder).Any()) Directory.Delete(folder);
                    });
                    return;
                }

                var existing = text == null ? null : StringsFile.Get(text, TrackingKey);
                if (existing != null && existing != value && existing != previous) {
                    conflicts.Add($"{file} {TrackingKey} is {Quote(existing)}, Consent's is {Quote(value)}");
                    return;
                }

                if (value == null) {
                    if (existing != null) changes.Add(() => File.WriteAllText(path, StringsFile.Set(text, TrackingKey, null), encoding));
                    if (text != null && !settings.ChildDirected && key != "base") untracked.Add($"{code}.lproj");
                    return;
                }

                if (text == null && !now.Created(key)) now.created.Add(code);
                changes.Add(() => {
                    Directory.CreateDirectory(Path.GetDirectoryName(path)!);
                    File.WriteAllText(path, StringsFile.Set(text ?? Header, TrackingKey, value), encoding);
                    if (files.Count == 0) project.AddLocaleVariantFile(StringsName, code, file);
                });
            }

            string Quote(string value) => value != null ? $"\"{value}\"" : settings.ChildDirected ? "none, the game is for children" : "none for this language";
        }

        /// <summary>
        /// Each language's InfoPlist.strings files the app will get, by TrackingPrompts.Key, with paths relative to the Xcode project: a file of a variant group or inside a folder reference the app target copies, or of the InfoPlist.strings group Consent adds its own files to; Unity's template has one for its test target, with an English file.
        /// </summary>
        private static Dictionary<string, List<XcodeResources.Entry>> AppStrings(string buildPath, string pbxproj, string resourcesPhase) {
            var result = new Dictionary<string, List<XcodeResources.Entry>>();
            foreach (var entry in XcodeResources.Copied(pbxproj, resourcesPhase, StringsName)) {
                var file   = entry.Folder ? entry.Path + "/" + StringsName : entry.Path;
                var folder = Path.GetFileName(Path.GetDirectoryName(file) ?? "");
                if (Path.GetFileName(file) != StringsName || !folder.EndsWith(".lproj", StringComparison.OrdinalIgnoreCase)) continue;
                if (entry.Folder && !File.Exists(Path.Combine(buildPath, file))) continue;

                var key = TrackingPrompts.Key(folder[..^".lproj".Length]);
                if (!result.TryGetValue(key, out var files)) result[key] = files = new List<XcodeResources.Entry>();
                if (files.All(other => other.Path != file)) files.Add(new XcodeResources.Entry(file, entry.Guid, entry.Folder));
            }

            return result;
        }

        private static (string text, Encoding encoding) Read(string path) {
            using var reader = new StreamReader(path, new UTF8Encoding(false), true);
            var text = reader.ReadToEnd();
            return (text, reader.CurrentEncoding);
        }

        private static string Describe(PlistElement element) => element is PlistElementString text ? $"\"{text.value}\"" : $"a {element.GetType().Name}";

        /// <summary>
        /// The values Consent wrote into this Xcode project the last time, kept beside it: a build that appends to the project finds them still there, and they are Consent's own, not another plugin's.
        /// </summary>
        [Serializable]
        private sealed class Written {
            private const string FileName = "RiseOnConsent.json";

            public string appId;
            public string tracking;
            public List<Language> languages = new();

            /// <summary>Every language Consent made a file for in this Xcode project, the ones it deleted since too.</summary>
            public List<string> created = new();

            public Language Language(string key) => languages.FirstOrDefault(language => TrackingPrompts.Key(language.code) == key);

            public bool Created(string key) => created.Any(code => TrackingPrompts.Key(code) == key);

            public static Written Read(string buildPath) {
                var path = Path.Combine(buildPath, FileName);
                return File.Exists(path) ? JsonUtility.FromJson<Written>(File.ReadAllText(path)) : new Written();
            }

            public void Write(string buildPath) {
                File.WriteAllText(Path.Combine(buildPath, FileName), JsonUtility.ToJson(this, true));
            }
        }

        [Serializable]
        private sealed class Language {
            public string code;
            public string text;
        }
    }
}
#endif